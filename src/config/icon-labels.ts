for (const [category, rows] of Object.entries(remixKeywords)) {
  for (const [name, keywords] of Object.entries(rows))
    metadata.set(name, { keywords, category: categoryNames[category] || '其他' })
}

export function describeRemixIcon(name: string) {
  const base = name.replace(/-(line|fill)$/, '')
  const plain = base.replace(/-\d+(?=-|$)/g, '')
  const data = metadata.get(base) || metadata.get(plain)
  const root = preferredKeys.find((key) => plain === key || plain.startsWith(key + '-'))
  const tail = root ? plain.slice(root.length).replace(/^-/, '').split('-').filter(Boolean) : []
  const chineseTags = data?.keywords.split(',').filter((x) => /[\u3400-\u9fff]/.test(x)) || []
  const translatedTail = tail.every((x) => suffixes[x]) ? tail.map((x) => suffixes[x]).join('') : ''
  const label = root
    ? names[root] + (translatedTail ? '·' + translatedTail : '')
    : chineseTags[0] || '其他图标'
  const number = base.match(/-([0-9]+)(?=-|$)/)?.[1]
  return {
    label:
      label +
      (number ? ' ' + number : '') +
      (name.endsWith('-fill') ? '·实心' : name.endsWith('-line') ? '·线条' : ''),
    keywords: data?.keywords || '',
    category: data?.category || '其他'
  }
}
